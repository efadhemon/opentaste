//! Non-destructive marker-block injection.
//!
//! `CLAUDE.md`, `.windsurfrules`, `AGENTS.md` and
//! `.github/copilot-instructions.md` all belong to the developer. OpenTaste
//! only owns the region between its two markers and must leave every byte
//! outside them alone, every time, forever.
//!
//! Two properties are load-bearing and tested directly:
//!
//! - **Idempotency.** Injecting the same body twice yields identical bytes, so
//!   a sync that changes nothing shows up in no diff.
//! - **Refusal over repair.** An unbalanced marker pair is reported as an error
//!   and the file is left untouched. Guessing where the block was meant to end
//!   is how handwritten content gets swallowed.

use std::path::Path;

use crate::error::{Error, Result};
use crate::storage::atomic::{read_to_string_opt, write_if_changed};

/// Opening marker written by OpenTaste.
pub const START_MARKER: &str =
    "<!-- OPENTASTE:START - AUTO-GENERATED BY OPENTASTE, DO NOT EDIT INSIDE THIS BLOCK -->";
/// Closing marker written by OpenTaste.
pub const END_MARKER: &str = "<!-- OPENTASTE:END -->";

/// Stable prefix used to *locate* an opening marker.
///
/// Matching on the prefix rather than the whole line means the human-readable
/// warning inside the marker can be reworded in a later release without
/// orphaning blocks written by an earlier one.
const START_PREFIX: &str = "<!-- OPENTASTE:START";

/// Where an existing block sits within a document.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct BlockSpan {
    /// Byte offset of the opening marker.
    start: usize,
    /// Byte offset just past the closing marker.
    end: usize,
}

/// Replace, or append, the OpenTaste block in `existing`.
///
/// `body` is the content that goes between the markers, without the markers
/// themselves. `path` is used only to name the file in an error.
pub fn inject(existing: &str, body: &str, path: &Path) -> Result<String> {
    let uses_crlf = detect_crlf(existing);
    let normalized = if uses_crlf {
        existing.replace("\r\n", "\n")
    } else {
        existing.to_string()
    };

    let block = render_block(body);
    let result = match locate_block(&normalized, path)? {
        Some(span) => splice(&normalized, span, &block),
        None => append(&normalized, &block),
    };

    Ok(if uses_crlf {
        result.replace('\n', "\r\n")
    } else {
        result
    })
}

/// Remove the OpenTaste block from `existing`, leaving everything else intact.
///
/// Returns `None` when there was no block to remove.
pub fn strip(existing: &str, path: &Path) -> Result<Option<String>> {
    let uses_crlf = detect_crlf(existing);
    let normalized = if uses_crlf {
        existing.replace("\r\n", "\n")
    } else {
        existing.to_string()
    };

    let Some(span) = locate_block(&normalized, path)? else {
        return Ok(None);
    };

    let mut result = String::with_capacity(normalized.len());
    result.push_str(normalized[..span.start].trim_end_matches('\n'));
    let trailing = normalized[span.end..].trim_start_matches('\n');
    if !trailing.is_empty() {
        result.push_str("\n\n");
        result.push_str(trailing);
    }
    if !result.is_empty() && !result.ends_with('\n') {
        result.push('\n');
    }

    Ok(Some(if uses_crlf {
        result.replace('\n', "\r\n")
    } else {
        result
    }))
}

/// Whether `contents` contains a complete OpenTaste block.
pub fn has_block(contents: &str) -> bool {
    let normalized = contents.replace("\r\n", "\n");
    matches!(
        locate_block(&normalized, Path::new("<memory>")),
        Ok(Some(_))
    )
}

/// Read `path`, inject `body`, and write the result back atomically.
///
/// Returns `true` when the file's bytes actually changed.
pub fn write_block(path: &Path, body: &str) -> Result<bool> {
    let existing = read_to_string_opt(path)?.unwrap_or_default();
    let updated = inject(&existing, body, path)?;
    write_if_changed(path, updated.as_bytes())
}

/// Read `path` and remove the OpenTaste block, leaving the rest in place.
///
/// Returns `true` when the file's bytes actually changed. A file consisting of
/// nothing but an OpenTaste block is deleted rather than left empty.
pub fn clear_block(path: &Path) -> Result<bool> {
    let Some(existing) = read_to_string_opt(path)? else {
        return Ok(false);
    };
    let Some(stripped) = strip(&existing, path)? else {
        return Ok(false);
    };

    if stripped.trim().is_empty() {
        return crate::storage::atomic::remove_if_present(path);
    }
    write_if_changed(path, stripped.as_bytes())
}

/// Assemble the marker-delimited block, body included.
fn render_block(body: &str) -> String {
    let trimmed = body.trim_matches('\n');
    if trimmed.is_empty() {
        format!("{START_MARKER}\n{END_MARKER}")
    } else {
        format!("{START_MARKER}\n\n{trimmed}\n\n{END_MARKER}")
    }
}

/// Find the first complete marker pair in `normalized` (LF-only) content.
fn locate_block(normalized: &str, path: &Path) -> Result<Option<BlockSpan>> {
    let Some(start) = normalized.find(START_PREFIX) else {
        // A closing marker with nothing to close is just as broken as the
        // reverse, and just as unsafe to repair by guessing.
        if normalized.contains(END_MARKER) {
            return Err(Error::MalformedMarkers {
                path: path.to_path_buf(),
            });
        }
        return Ok(None);
    };

    // The opening marker is an HTML comment; it must actually be closed.
    let Some(start_marker_end) = normalized[start..].find("-->").map(|i| start + i + 3) else {
        return Err(Error::MalformedMarkers {
            path: path.to_path_buf(),
        });
    };

    let Some(end_offset) = normalized[start_marker_end..].find(END_MARKER) else {
        return Err(Error::MalformedMarkers {
            path: path.to_path_buf(),
        });
    };

    Ok(Some(BlockSpan {
        start,
        end: start_marker_end + end_offset + END_MARKER.len(),
    }))
}

/// Replace an existing block in place, preserving surrounding content exactly.
fn splice(normalized: &str, span: BlockSpan, block: &str) -> String {
    let mut result = String::with_capacity(normalized.len() + block.len());
    result.push_str(&normalized[..span.start]);
    result.push_str(block);
    result.push_str(&normalized[span.end..]);

    if !result.ends_with('\n') {
        result.push('\n');
    }
    result
}

/// Append a block to a document that has none, separated by one blank line.
fn append(normalized: &str, block: &str) -> String {
    let existing = normalized.trim_end_matches('\n');
    if existing.is_empty() {
        return format!("{block}\n");
    }
    format!("{existing}\n\n{block}\n")
}

/// Whether a document uses Windows line endings.
///
/// Mixed endings are treated as LF, since rewriting a file wholesale to CRLF on
/// the strength of one stray `\r\n` would be a surprising amount of churn.
fn detect_crlf(contents: &str) -> bool {
    let crlf = contents.matches("\r\n").count();
    crlf > 0 && crlf == contents.matches('\n').count()
}

#[cfg(test)]
mod tests {
    use super::*;
    use pretty_assertions::assert_eq;

    fn p() -> &'static Path {
        Path::new("CLAUDE.md")
    }

    #[test]
    fn an_empty_document_gets_just_the_block() {
        let out = inject("", "- Rule one", p()).unwrap();
        assert_eq!(
            out,
            format!("{START_MARKER}\n\n- Rule one\n\n{END_MARKER}\n")
        );
    }

    #[test]
    fn an_existing_document_keeps_its_content_and_gains_a_block_at_the_end() {
        let existing = "# My Project\n\nSome handwritten notes.\n";
        let out = inject(existing, "- Rule one", p()).unwrap();

        assert!(out.starts_with(existing), "{out}");
        assert!(out.contains("- Rule one"), "{out}");
        assert!(out.ends_with(&format!("{END_MARKER}\n")), "{out}");
    }

    #[test]
    fn content_above_and_below_the_block_is_preserved_verbatim() {
        let existing = format!(
            "# Above\n\nKeep me.\n\n{START_MARKER}\n\n- Old rule\n\n{END_MARKER}\n\n# Below\n\nKeep me too.\n"
        );

        let out = inject(&existing, "- New rule", p()).unwrap();

        assert!(out.starts_with("# Above\n\nKeep me.\n\n"), "{out}");
        assert!(out.ends_with("\n\n# Below\n\nKeep me too.\n"), "{out}");
        assert!(out.contains("- New rule"), "{out}");
        assert!(!out.contains("- Old rule"), "{out}");
    }

    #[test]
    fn injecting_the_same_body_twice_is_byte_identical() {
        let documents = [
            "",
            "# Project\n",
            "# Project\n\nNotes without a trailing newline",
            &format!("Before\n\n{START_MARKER}\n\n- Old\n\n{END_MARKER}\n\nAfter\n"),
        ];

        for document in documents {
            let once = inject(document, "- Rule one\n- Rule two", p()).unwrap();
            let twice = inject(&once, "- Rule one\n- Rule two", p()).unwrap();
            assert_eq!(once, twice, "not idempotent for {document:?}");
        }
    }

    #[test]
    fn an_opening_marker_without_a_closing_one_is_refused() {
        let existing = format!("# Project\n\n{START_MARKER}\n\n- Half a block\n");
        let err = inject(&existing, "- Rule", p()).unwrap_err();

        assert!(matches!(err, Error::MalformedMarkers { .. }));
        assert!(err.to_string().contains("CLAUDE.md"), "{err}");
    }

    #[test]
    fn a_closing_marker_without_an_opening_one_is_refused() {
        let existing = format!("# Project\n\n- Orphan\n\n{END_MARKER}\n");
        let err = inject(&existing, "- Rule", p()).unwrap_err();
        assert!(matches!(err, Error::MalformedMarkers { .. }));
    }

    #[test]
    fn a_closing_marker_before_its_opening_one_is_refused() {
        let existing = format!("{END_MARKER}\n\nmiddle\n\n{START_MARKER}\n");
        let err = inject(&existing, "- Rule", p()).unwrap_err();
        assert!(matches!(err, Error::MalformedMarkers { .. }));
    }

    #[test]
    fn an_unterminated_opening_comment_is_refused() {
        let existing = "<!-- OPENTASTE:START never closed\n\nbody\n";
        let err = inject(existing, "- Rule", p()).unwrap_err();
        assert!(matches!(err, Error::MalformedMarkers { .. }));
    }

    #[test]
    fn only_the_first_of_several_blocks_is_rewritten() {
        let existing = format!(
            "{START_MARKER}\n\n- First\n\n{END_MARKER}\n\nmiddle\n\n{START_MARKER}\n\n- Second\n\n{END_MARKER}\n"
        );

        let out = inject(&existing, "- Replacement", p()).unwrap();

        assert!(out.contains("- Replacement"), "{out}");
        assert!(!out.contains("- First"), "{out}");
        assert!(
            out.contains("- Second"),
            "a stray second block must be left for the developer to resolve: {out}"
        );
    }

    #[test]
    fn a_block_written_by_an_older_marker_wording_is_still_recognised() {
        let legacy = "<!-- OPENTASTE:START -->";
        let existing = format!("# Project\n\n{legacy}\n\n- Old rule\n\n{END_MARKER}\n");

        let out = inject(&existing, "- New rule", p()).unwrap();

        assert!(out.contains(START_MARKER), "marker upgraded: {out}");
        assert!(!out.contains("- Old rule"), "{out}");
        assert_eq!(out.matches(START_PREFIX).count(), 1, "{out}");
        assert_eq!(out.matches(END_MARKER).count(), 1, "{out}");
    }

    #[test]
    fn windows_line_endings_are_preserved() {
        let existing = "# Project\r\n\r\nNotes.\r\n";
        let out = inject(existing, "- Rule one", p()).unwrap();

        assert!(out.starts_with("# Project\r\n"), "{out:?}");
        assert!(!out.contains("\n\n"), "no bare LF should survive: {out:?}");
        assert!(out.ends_with("\r\n"), "{out:?}");

        // And re-injecting keeps them, rather than flipping the file to LF.
        assert_eq!(inject(&out, "- Rule one", p()).unwrap(), out);
    }

    #[test]
    fn a_document_with_mixed_endings_keeps_them_and_writes_its_own_block_as_lf() {
        // One stray CRLF is not reason enough to rewrite the whole document, so
        // the existing bytes pass through untouched and our block uses LF.
        let existing = "# Project\n\r\nNotes.\n";
        let out = inject(existing, "- Rule", p()).unwrap();

        assert!(out.starts_with("# Project\n\r\nNotes."), "{out:?}");
        assert!(out.ends_with(&format!("{END_MARKER}\n")), "{out:?}");
        assert_eq!(out.matches("\r\n").count(), 1, "{out:?}");
    }

    #[test]
    fn an_empty_body_writes_an_empty_but_well_formed_block() {
        let out = inject("# Project\n", "", p()).unwrap();
        assert!(
            out.contains(&format!("{START_MARKER}\n{END_MARKER}")),
            "{out}"
        );
        assert!(has_block(&out));
    }

    #[test]
    fn the_result_always_ends_with_exactly_one_newline() {
        for document in ["", "# Project", "# Project\n\n\n"] {
            let out = inject(document, "- Rule", p()).unwrap();
            assert!(out.ends_with('\n'), "{out:?}");
            assert!(!out.ends_with("\n\n"), "{out:?}");
        }
    }

    #[test]
    fn has_block_only_reports_complete_pairs() {
        assert!(!has_block("# Project\n"));
        assert!(!has_block(&format!("{START_MARKER}\nunterminated\n")));
        assert!(has_block(&format!("{START_MARKER}\n{END_MARKER}")));
    }

    #[test]
    fn stripping_restores_the_document_the_developer_wrote() {
        let original = "# Above\n\nKeep me.\n\n# Below\n\nKeep me too.\n";
        let injected = inject(original, "- Rule one", p()).unwrap();

        let stripped = strip(&injected, p()).unwrap().expect("a block to remove");
        assert_eq!(stripped, original);
    }

    #[test]
    fn stripping_a_document_without_a_block_reports_nothing_to_do() {
        assert_eq!(strip("# Project\n", p()).unwrap(), None);
    }

    #[test]
    fn stripping_the_only_content_leaves_an_empty_document() {
        let injected = inject("", "- Rule", p()).unwrap();
        assert_eq!(strip(&injected, p()).unwrap(), Some(String::new()));
    }

    #[test]
    fn writing_to_disk_is_a_no_op_when_nothing_changed() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("CLAUDE.md");
        std::fs::write(&path, "# Project\n\nHandwritten.\n").unwrap();

        assert!(write_block(&path, "- Rule one").unwrap());
        let first = std::fs::read(&path).unwrap();

        assert!(!write_block(&path, "- Rule one").unwrap());
        assert_eq!(std::fs::read(&path).unwrap(), first);

        assert!(write_block(&path, "- Rule two").unwrap());
    }

    #[test]
    fn a_malformed_file_is_left_exactly_as_it_was_found() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("CLAUDE.md");
        let broken = format!("# Project\n\n{START_MARKER}\n\n- Half a block\n");
        std::fs::write(&path, &broken).unwrap();

        assert!(write_block(&path, "- Rule").is_err());
        assert_eq!(std::fs::read_to_string(&path).unwrap(), broken);
    }

    #[test]
    fn clearing_removes_the_block_but_keeps_the_file_when_anything_else_remains() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("CLAUDE.md");
        std::fs::write(&path, "# Project\n\nHandwritten.\n").unwrap();
        write_block(&path, "- Rule one").unwrap();

        assert!(clear_block(&path).unwrap());
        assert_eq!(
            std::fs::read_to_string(&path).unwrap(),
            "# Project\n\nHandwritten.\n"
        );
        assert!(!clear_block(&path).unwrap(), "nothing left to clear");
    }

    #[test]
    fn clearing_deletes_a_file_opentaste_created_on_its_own() {
        let tmp = tempfile::tempdir().unwrap();
        let path = tmp.path().join("CLAUDE.md");
        write_block(&path, "- Rule one").unwrap();

        assert!(clear_block(&path).unwrap());
        assert!(
            !path.exists(),
            "a file holding nothing but our block should not be left behind empty"
        );
        assert!(!clear_block(&path).unwrap());
    }
}
